CREATE TABLE IF NOT EXISTS rules (account TEXT PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS stats (rule_id TEXT NOT NULL, key TEXT NOT NULL, n INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (rule_id, key));
CREATE TABLE IF NOT EXISTS seen (key TEXT PRIMARY KEY, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS retry (cid TEXT PRIMARY KEY, account TEXT NOT NULL, rule_id TEXT NOT NULL, at INTEGER NOT NULL);
